"""
例題 02-5: 区間加算

入力:
N Q
L1 R1 X1
L2 R2 X2
...
LQ RQ XQ

最初、長さ N の整数列 A の全要素は 0 である。
各操作について、A の L 番目から R 番目までの全要素に X を加える。
全ての操作を終えた後の A を空白区切りで出力する。

制約:
- 1 <= N, Q <= 200000
- 1 <= Li <= Ri <= N
- -1000000000 <= Xi <= 1000000000

例:
入力
6 3
1 3 5
2 5 2
4 6 -1

出力
5 7 7 1 1 -1
"""

def main():
    n, q = map(int, input().split())

    # a[i] には最終的な値ではなく、直前の位置からの変化量を記録する。
    a = [0] * n

    for _ in range(q):
        l, r, x = map(int, input().split())

        # 1-indexed の閉区間 [l, r] に x を加える。
        # l の位置で +x を開始し、r の次の位置で -x を行って加算を終了する。
        a[l - 1] += x

        # r == n の場合、加算終了位置は配列の外側なので記録しなくてよい。
        if r < n:
            a[r] -= x

    # 変化量の累積和を取ることで、各位置の最終的な値を復元する。
    for i in range(1, n):
        a[i] += a[i - 1]

    print(" ".join(map(str, a)))


if __name__ == "__main__":
    main()
