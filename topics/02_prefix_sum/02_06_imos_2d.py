"""
例題 02-6: 長方形領域への一括加算

入力:
H W Q
R1_1 C1_1 R2_1 C2_1 X1
R1_2 C1_2 R2_2 C2_2 X2
...
R1_Q C1_Q R2_Q C2_Q XQ

最初、H 行 W 列の整数グリッド A の全要素は 0 である。
各操作について、左上が (R1, C1)、右下が (R2, C2) の長方形領域に
含まれる全てのマスへ X を加える。

全ての操作を終えた後の A を、各行ごとに空白区切りで出力する。
行番号と列番号は 1-indexed とし、長方形の境界上のマスも含む。

制約:
- 1 <= H, W <= 1000
- 1 <= Q <= 200000
- 1 <= R1 <= R2 <= H
- 1 <= C1 <= C2 <= W
- -1000000000 <= X <= 1000000000

例:
入力
3 4 3
1 1 2 2 5
2 2 3 4 2
1 3 3 3 -1

出力
5 5 -1 0
5 7 1 2
0 2 1 2
"""


def main():
    # 二次元いもす法で、長方形の四隅にどの符号で値を置くか、
    # その後にどの方向へ累積和を取るかを自力で組み立てられなかった。
    pass


def model_answer():
    h, w, q = map(int, input().split())

    # 右端や下端の次の位置にも差分を書けるように、
    # 元のグリッドより1行・1列大きい差分配列を用意する。
    diff = [[0] * (w + 1) for _ in range(h + 1)]

    for _ in range(q):
        r1, c1, r2, c2, x = map(int, input().split())

        # 1-indexed の閉じた長方形 [r1, r2] x [c1, c2] に x を加える。
        #
        # 左上で +x を開始する。
        # 右上と左下で -x を置き、横方向・縦方向への広がりを止める。
        # 右下で +x を置き、2回引かれる領域を1回分足し戻す。
        diff[r1 - 1][c1 - 1] += x
        diff[r1 - 1][c2] -= x
        diff[r2][c1 - 1] -= x
        diff[r2][c2] += x

    # 各行について左から右へ累積和を取り、横方向の変化量を復元する。
    for r in range(h + 1):
        for c in range(1, w + 1):
            diff[r][c] += diff[r][c - 1]

    # 各列について上から下へ累積和を取り、縦方向の変化量を復元する。
    # 横方向と縦方向の両方を復元すると、各マスの最終値になる。
    for c in range(w + 1):
        for r in range(1, h + 1):
            diff[r][c] += diff[r - 1][c]

    for r in range(h):
        print(*diff[r][:w])


if __name__ == "__main__":
    main()
